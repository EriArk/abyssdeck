export const helpArticle = (id: string) => helpArticles.find((article) => article.id === id);
const normalize = (text: string) => text.toLocaleLowerCase("ru").replaceAll("ё", "е");
const searchable = helpArticles.map((article) => ({
  article,
  text: normalize(
    [
      article.title,
      article.summary,
      article.category,
      article.group,
      article.keywords,
      ...article.sections.flatMap((section) => [
        section.title,
        ...section.paragraphs,
        ...(section.steps ?? []),
        ...(section.bullets ?? []),
      ]),
    ].join(" "),
  ),
}));
export function searchHelp(query: string): HelpArticle[] {
  const words = normalize(query.trim()).split(/\s+/).filter(Boolean);
  return searchable
    .filter(({ text }) => words.every((word) => text.includes(word)))
    .map(({ article }) => article);
}
